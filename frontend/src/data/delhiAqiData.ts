/**
 * Find record by exact date string (YYYY-MM-DD)
 */
export function getRecordByDate(dateStr: string): DailyAqiRecord {
  const match = DAILY_AQI_DATABASE.find(r => r.date === dateStr);
  if (match) return match;
  // Default to Peak Severe Episode if not found
  return DAILY_AQI_DATABASE.find(r => r.date === '2025-11-18') || DAILY_AQI_DATABASE[0];
}

/**
 * Returns a 15-day contiguous window around or terminating at the given date
 */
export function get15DayWindow(targetDateStr: string): DailyAqiRecord[] {
  const idx = DAILY_AQI_DATABASE.findIndex(r => r.date === targetDateStr);
  if (idx === -1) {
    // Default to the 15 days around Peak Severe
    const peakIdx = DAILY_AQI_DATABASE.findIndex(r => r.date === '2025-11-18');
    const start = Math.max(0, peakIdx - 7);
    return DAILY_AQI_DATABASE.slice(start, start + 15);
  }

  // Position targetDate around index 7 (middle) if possible, or shift to stay in bounds
  let start = idx - 7;
  if (start < 0) start = 0;
  if (start + 15 > DAILY_AQI_DATABASE.length) {
    start = Math.max(0, DAILY_AQI_DATABASE.length - 15);
  }
  return DAILY_AQI_DATABASE.slice(start, start + 15);
}

/**
 * Calculate MAE, RMSE, and Baseline MAE for a given window
 */
export function calculateWindowMetrics(records: DailyAqiRecord[]) {
  if (!records.length) return { modelMae: 0, baselineMae: 0, modelRmse: 0, skillScore: 0 };
  let sumAbsError = 0;
  let sumSqError = 0;
  let sumBaselineAbsError = 0;

  for (const r of records) {
    sumAbsError += Math.abs(r.error);
    sumSqError += r.error * r.error;
    sumBaselineAbsError += Math.abs(r.baselineAQI - r.derivedActualAQI);
  }

  const n = records.length;
  const modelMae = +(sumAbsError / n).toFixed(1);
  const modelRmse = +Math.sqrt(sumSqError / n).toFixed(1);
  const baselineMae = +(sumBaselineAbsError / n).toFixed(1);
  const skillScore = baselineMae > 0 ? +(((baselineMae - modelMae) / baselineMae) * 100).toFixed(1) : 0;

  return { modelMae, baselineMae, modelRmse, skillScore };
}
